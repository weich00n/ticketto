"""Make a plain RabbitMQ look like the team broker, as far as Ticket can tell.

The real broker (rabbitmq-service) creates every exchange, queue and policy from its
topology/messages.yaml, and gives each service its own least-privilege user. Ticket never
declares any of that itself, so local stacks and CI need it set up first. This script:

  1. imports ticket-topology.json (Ticket's slice of rabbitmq-service's
     topology/definitions.json: its consumer queues, their DLQs, the exchanges and policies)
     through the management API;
  2. creates the `ticket-service` user with the same permissions as on the real broker
     (topology/service-users.tsv): declare and publish only to ticket.events, consume only
     its own `ticket-service.<Message>` queues.

Standard library only, so it runs in a bare python image:

    python scripts/broker/setup_broker.py --management-url http://localhost:15672

The admin login comes from RABBITMQ_ADMIN_USER / RABBITMQ_ADMIN_PASS and Ticket's password
from TICKET_RABBITMQ_PASSWORD (all default to the local `ticketto-local`, as in
rabbitmq-service). When ticket-topology.json changes there, copy the new slice here.
"""

import argparse
import base64
import json
import os
import sys
import time
import urllib.error
import urllib.parse
import urllib.request
from pathlib import Path

TOPOLOGY = Path(__file__).with_name("ticket-topology.json")
LOCAL_PASSWORD = "ticketto-local"  # local and CI only; gitleaks:allow
USER = "ticket-service"
# As generated by rabbitmq-service's tools/generate_definitions.py for ticket-service.
PERMISSIONS = {
    "configure": r"^ticket\.events$",
    "write": r"^ticket\.events$",
    "read": r"^ticket-service\.[A-Za-z]+$",
}
TOPIC_PERMISSIONS = {"exchange": "ticket.events", "write": r"^(ticket\.issued)$", "read": ".*"}


class Management:
    def __init__(self, base_url: str, user: str, password: str):
        self.base_url = base_url.rstrip("/")
        token = base64.b64encode(f"{user}:{password}".encode()).decode()
        self.auth = f"Basic {token}"

    def _request(self, method: str, path: str, body: object | None = None) -> None:
        request = urllib.request.Request(
            f"{self.base_url}/api/{path}",
            data=None if body is None else json.dumps(body).encode(),
            method=method,
            headers={"Content-Type": "application/json", "Authorization": self.auth},
        )
        with urllib.request.urlopen(request, timeout=30):  # raises on any non-2xx answer
            pass

    def call(self, method: str, path: str, body: object | None = None) -> None:
        try:
            self._request(method, path, body)
        except urllib.error.HTTPError as error:
            detail = error.read().decode(errors="replace")[:500]
            raise SystemExit(f"{method} /api/{path} failed: {error.code} {detail}") from error

    def wait_until_ready(self, timeout: float) -> None:
        deadline = time.monotonic() + timeout
        while True:
            try:
                self._request("GET", "overview")
                return
            except (urllib.error.URLError, OSError) as error:  # includes HTTP errors while starting
                if time.monotonic() > deadline:
                    raise SystemExit(f"RabbitMQ management API not reachable: {error}") from error
                time.sleep(2)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--management-url", default="http://localhost:15672")
    parser.add_argument("--timeout", type=float, default=120, help="seconds to wait for it")
    args = parser.parse_args()

    api = Management(
        args.management_url,
        os.environ.get("RABBITMQ_ADMIN_USER", "ticketto"),
        os.environ.get("RABBITMQ_ADMIN_PASS", LOCAL_PASSWORD),
    )
    api.wait_until_ready(args.timeout)

    vhost = urllib.parse.quote("/", safe="")
    api.call("POST", "definitions", json.loads(TOPOLOGY.read_text(encoding="utf-8")))
    password = os.environ.get("TICKET_RABBITMQ_PASSWORD", LOCAL_PASSWORD)
    api.call("PUT", f"users/{USER}", {"password": password, "tags": ""})
    api.call("PUT", f"permissions/{vhost}/{USER}", PERMISSIONS)
    api.call("PUT", f"topic-permissions/{vhost}/{USER}", TOPIC_PERMISSIONS)
    print(f"Broker ready: Ticket's queues imported and user {USER} created.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
